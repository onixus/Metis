// EC07–EC11: real API/browser acceptance. Run against visual-stand-ds56.py; synthetic inputs only.
const { chromium } = require(process.env.METIS_PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.METIS_ACCEPTANCE_URL;
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname));
const root = process.env.METIS_ACCEPTANCE_TEMP;
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json')));
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.METIS_CHROMIUM_PATH ? { executablePath: process.env.METIS_CHROMIUM_PATH } : {}) });
  const results = [];
  try {
    for (const theme of ['dark', 'light']) {
      const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: theme });
      await ctx.addInitScript(({ token, theme }) => { sessionStorage.setItem('metis.access_token', token); localStorage.setItem('apex.theme', theme); }, { token: tokens.finance, theme });
      const page = await ctx.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      const run = Date.now();
      const field = `acceptance_${theme}_${run}`, metric = `result_${theme}_${run}`, bookMetric = `book_${theme}_${run}`;
      await page.goto(base + '/economics');
      await page.getByLabel('Период', { exact: true }).fill('2026-09');
      const productId = await page.getByLabel('Владелец финансовой книги').inputValue();
      await page.getByRole('tab', { name: 'Конструктор модели', exact: true }).click();
      await page.getByLabel('Ключ поля', { exact: true }).fill(field);
      await page.getByLabel('Название поля', { exact: true }).fill('Синтетическое ручное поле');
      await page.getByLabel('Тип поля').selectOption('number');
      await page.getByLabel('Источник поля').selectOption('manual');
      await page.getByRole('button', { name: 'Сохранить поле', exact: true }).click();
      await page.getByRole('button', { name: `Изменить поле ${field}`, exact: true }).waitFor();
      await page.getByLabel(`Значение ${field} (точное десятичное)`, { exact: true }).fill('9007199254740993.01');
      await page.getByRole('button', { name: `Сохранить значение ${field}`, exact: true }).click();
      await page.getByText('Значение сохранено · версия данных', { exact: false }).waitFor();
      await page.getByRole('tab', { name: 'Формулы и версии', exact: true }).click();
      await page.getByLabel('Ключ показателя', { exact: true }).fill(metric);
      await page.getByLabel('Название показателя', { exact: true }).fill('Синтетический расчёт');
      await page.getByLabel('Выражение формулы').fill(`field("${field}")`);
      await page.getByRole('button', { name: 'Сохранить показатель', exact: true }).click();
      await page.getByRole('button', { name: `Рассчитать и объяснить ${metric}`, exact: true }).click();
      await page.getByText(`${metric}: 9007199254740993.01`, { exact: true }).waitFor();
      await page.getByRole('button', { name: `Изменить формулу ${metric}`, exact: true }).click();
      await page.getByLabel('Выражение формулы').fill(`field("${field}") + d("0.01")`);
      await page.getByLabel('Дата действия формулы', { exact: true }).fill('2026-09-01');
      await page.getByRole('button', { name: 'Сохранить версию формулы', exact: true }).click();
      await page.getByRole('button', { name: `Сравнить формулы ${metric}`, exact: true }).click();
      await page.getByText('На данных периода 2026-09: v1 =', { exact: false }).waitFor();
      const comparison = await page.getByText('На данных периода 2026-09: v1 =', { exact: false }).innerText();
      assert.ok(comparison.includes('9007199254740993.01') && comparison.includes('9007199254740993.02'));
      await page.getByRole('button', { name: `Изменить формулу ${metric}`, exact: true }).click();
      await page.getByLabel('Выражение формулы').fill(`metric("${metric}")`);
      const invalid = page.waitForResponse(r => r.url().endsWith('/economics/metrics') && r.request().method() === 'POST');
      await page.getByRole('button', { name: 'Сохранить версию формулы', exact: true }).click();
      assert.equal((await invalid).status(), 409);
      assert.equal(await page.getByRole('button', { name: 'Сохранить версию формулы', exact: true }).count(), 1);
      await page.getByRole('button', { name: 'Отменить редактирование', exact: true }).click();
      await page.getByLabel('Ключ показателя', { exact: true }).fill(bookMetric);
      await page.getByLabel('Название показателя', { exact: true }).fill('Половина выручки книги');
      await page.getByLabel('Выражение формулы').fill('field("revenue") / d("2")');
      await page.getByRole('button', { name: 'Сохранить показатель', exact: true }).click();
      await page.getByRole('button', { name: `Изменить формулу ${bookMetric}`, exact: true }).waitFor();
      for (const width of [1440, 390]) {
        await page.setViewportSize({ width, height: 1000 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'constructor overflow');
        await page.screenshot({ path: path.join(root, `constructor-${theme}-${width}.png`), fullPage: true });
      }
      const scenarioName = `Synthetic ${theme} ${run}`;
      await page.getByRole('tab', { name: 'Сценарии бюджета и capacity', exact: true }).click();
      await page.getByLabel('Название сценария', { exact: true }).fill(scenarioName);
      await page.getByLabel('Сдвиг capacity в днях', { exact: true }).fill('3');
      await page.getByLabel('Дельта бюджета в основных единицах', { exact: true }).fill('-100,25');
      await page.getByRole('button', { name: 'Добавить подмену входа', exact: true }).click();
      await page.getByLabel('Поле подмены 1', { exact: true }).selectOption(field);
      await page.getByLabel('Новое значение входа 1', { exact: true }).fill('9007199254740993.02');
      await page.getByRole('button', { name: 'Сохранить сценарий', exact: true }).click();
      await page.getByRole('button', { name: `Рассчитать сценарий ${scenarioName}`, exact: true }).waitFor();
      await page.getByRole('checkbox', { name: metric, exact: true }).check();
      await page.getByRole('button', { name: `Рассчитать сценарий ${scenarioName}`, exact: true }).click();
      await page.getByRole('heading', { name: `Результат сценария «${scenarioName}»`, exact: true }).waitFor();
      await page.getByRole('cell', { name: '9007199254740993.03', exact: true }).waitFor();
      // Reconciliation is exercised through the same public import UI after initial data/configuration.
      const file = `product_id,period,category,amount,currency,description\n${productId},2026-09,revenue,100,RUB,Synthetic acceptance\n`;
      await page.getByRole('tab', { name: 'Книга периода', exact: true }).click();
      await page.getByRole('tab', { name: 'Загрузить данные', exact: true }).click();
      await page.getByLabel('Файл', { exact: true }).setInputFiles({ name: 'synthetic.csv', mimeType: 'text/csv', buffer: Buffer.from(file) });
      await page.getByRole('button', { name: 'Предпросмотр', exact: true }).click();
      await page.getByText('Корректных строк: 1. Ошибок: 0.', { exact: true }).waitFor();
      await page.getByRole('button', { name: /^Сохранить версию / }).click();
      await page.getByRole('tab', { name: 'Загрузить данные', exact: true }).click();
      const preserve = page.getByLabel('Сопоставить строки и сохранить доли и ручные значения', { exact: true });
      assert.equal(await preserve.count(), 1);
      await preserve.check();
      await page.getByLabel('Файл', { exact: true }).setInputFiles({ name: 'synthetic.csv', mimeType: 'text/csv', buffer: Buffer.from(file.replace(',100,RUB', ',125,RUB')) });
      await page.getByRole('button', { name: 'Предпросмотр', exact: true }).click();
      await page.getByText('Корректных строк: 1. Ошибок: 0.', { exact: true }).waitFor();
      const request = page.waitForRequest(r => r.url().endsWith('/import') && r.method() === 'POST');
      await page.getByRole('button', { name: /^Сохранить версию / }).click();
      assert.equal((await request).postDataJSON().preserve_rules, true);
      await page.getByRole('heading', { name: 'P&L по продуктам', exact: true }).waitFor();
      assert.equal(await page.getByLabel('Формула конструктора').count(), 1, 'One shared formula panel after version changes');
      await page.getByLabel('Формула конструктора').selectOption(bookMetric);
      const bookResponse = page.waitForResponse(r => r.url().includes(`/metrics/${bookMetric}?`) && r.request().method() === 'GET');
      await page.getByRole('button', { name: /^Рассчитать на книге v/ }).click();
      const calculatedBook = await bookResponse;
      assert.equal(calculatedBook.status(), 200);
      assert.ok(Number(new URL(calculatedBook.url()).searchParams.get('version')) > 0, 'Pinned book version');
      await page.getByText(`${bookMetric}: 6250`, { exact: true }).waitFor();
      assert.deepEqual(errors, []);
      results.push({ theme, manualValue: 'exact decimal', formulaVersions: 'PASS', explain: 'PASS', cycleRejected: 409, reconciliation: 'PASS', sharedBookFormula: 'PASS', savedBudgetCapacityScenario: 'PASS', mobile: 'PASS' });
      await ctx.close();
    }
    fs.writeFileSync(path.join(root, 'economics-acceptance.json'), JSON.stringify({ testedAt: new Date().toISOString(), results }, null, 2));
    console.log(JSON.stringify(results));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
